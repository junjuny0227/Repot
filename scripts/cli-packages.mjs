// Renders the Homebrew formula and the Scoop manifest for the repot CLI (plan 15, Task 5).
// The release workflow downloads the `.sha256` files of a published release and runs
//   node scripts/cli-packages.mjs <tag> <dir with .sha256 files> <out dir>
// which writes <out>/Formula/repot.rb and <out>/bucket/repot.json. The templates live here,
// not in the tap/bucket repositories, so they are reviewed with the code that builds the archives.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = 'junjuny0227/Repot';
export const DESCRIPTION = 'Scan a development machine and export a script that restores it';
export const TARGETS = {
  macArm: 'aarch64-apple-darwin',
  macIntel: 'x86_64-apple-darwin',
  linuxIntel: 'x86_64-unknown-linux-gnu',
  windows: 'x86_64-pc-windows-msvc',
};

export function archiveName(version, target) {
  const ext = target.includes('windows') ? 'zip' : 'tar.gz';
  return `repot-cli-${version}-${target}.${ext}`;
}

function downloadUrl(tag, file) {
  return `https://github.com/${REPO}/releases/download/${tag}/${file}`;
}

/** Version from a release tag (`v0.8.0` → `0.8.0`); anything else is an error. */
export function versionOf(tag) {
  const match = /^v(\d+\.\d+\.\d+)$/.exec(tag ?? '');
  if (!match) throw new Error(`not a release tag: ${tag}`);
  return match[1];
}

/** The hash from a `sha256sum` / `shasum -a 256` line. */
export function parseSha256(text, file) {
  const match = /^([0-9a-f]{64})\s+\*?(\S+)\s*$/i.exec(text.trim());
  if (!match) throw new Error(`${file}.sha256: no sha256 line`);
  if (match[2] !== file) throw new Error(`${file}.sha256: names ${match[2]}`);
  return match[1].toLowerCase();
}

export function formula(tag, sha) {
  const version = versionOf(tag);
  const asset = (target) => `      url "${downloadUrl(tag, archiveName(version, target))}"
      sha256 "${sha[target]}"`;
  return `# Generated by scripts/cli-packages.mjs in ${REPO}; do not edit by hand.
class Repot < Formula
  desc "${DESCRIPTION}"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
${asset(TARGETS.macArm)}
    end
    on_intel do
${asset(TARGETS.macIntel)}
    end
  end

  on_linux do
    on_intel do
${asset(TARGETS.linuxIntel)}
    end
  end

  def install
    bin.install "repot"
  end

  test do
    assert_equal "repot #{version}", shell_output("#{bin}/repot --version").strip
  end
end
`;
}

export function scoopManifest(tag, sha) {
  const version = versionOf(tag);
  const target = TARGETS.windows;
  const folder = (v) => `repot-cli-${v}-${target}`;
  const manifest = {
    version,
    description: DESCRIPTION,
    homepage: `https://github.com/${REPO}`,
    license: 'Apache-2.0',
    architecture: {
      '64bit': {
        url: downloadUrl(tag, archiveName(version, target)),
        hash: sha[target],
        extract_dir: folder(version),
      },
    },
    bin: 'repot.exe',
    checkver: 'github',
    autoupdate: {
      architecture: {
        '64bit': {
          url: downloadUrl('v$version', archiveName('$version', target)),
          extract_dir: folder('$version'),
          hash: { url: '$url.sha256' },
        },
      },
    },
  };
  return `${JSON.stringify(manifest, null, 4)}\n`;
}

export function render(tag, shaDir) {
  const version = versionOf(tag);
  const sha = {};
  for (const target of Object.values(TARGETS)) {
    const file = archiveName(version, target);
    sha[target] = parseSha256(readFileSync(join(shaDir, `${file}.sha256`), 'utf8'), file);
  }
  return { 'Formula/repot.rb': formula(tag, sha), 'bucket/repot.json': scoopManifest(tag, sha) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [tag, shaDir, outDir] = process.argv.slice(2);
  if (!tag || !shaDir || !outDir) {
    console.error('Usage: node scripts/cli-packages.mjs <tag> <sha256 dir> <out dir>');
    process.exit(2);
  }
  try {
    for (const [path, text] of Object.entries(render(tag, shaDir))) {
      const full = join(outDir, path);
      mkdirSync(join(full, '..'), { recursive: true });
      writeFileSync(full, text);
      console.log(`wrote ${full}`);
    }
  } catch (error) {
    console.error(`error: ${error.message}`);
    process.exit(1);
  }
}
